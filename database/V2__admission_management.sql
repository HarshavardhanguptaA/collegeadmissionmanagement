-- Safe, additive migration for a database that already contains the original
-- Student Management System's `students` and `courses` tables.
-- Back up the database first. Run this while connected to the target database.
-- For a brand-new database, start the Spring Boot app first so Hibernate creates
-- the original tables; this script is then safe to run as an idempotent schema check.

BEGIN;

ALTER TABLE students ADD COLUMN IF NOT EXISTS qualification VARCHAR(120);
ALTER TABLE students ADD COLUMN IF NOT EXISTS marks_percentage NUMERIC(5,2);

ALTER TABLE courses ADD COLUMN IF NOT EXISTS department VARCHAR(120) NOT NULL DEFAULT 'General';
ALTER TABLE courses ADD COLUMN IF NOT EXISTS duration_years INTEGER NOT NULL DEFAULT 4;
ALTER TABLE courses ADD COLUMN IF NOT EXISTS total_seats INTEGER NOT NULL DEFAULT 60;
ALTER TABLE courses ADD COLUMN IF NOT EXISTS active BOOLEAN NOT NULL DEFAULT TRUE;

CREATE TABLE IF NOT EXISTS user_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('STUDENT', 'ADMIN')),
    student_id BIGINT UNIQUE REFERENCES students(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS admission_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_number VARCHAR(40) NOT NULL UNIQUE,
    student_id BIGINT NOT NULL REFERENCES students(id),
    course_id BIGINT NOT NULL REFERENCES courses(id),
    qualification VARCHAR(120) NOT NULL,
    marks_percentage NUMERIC(5,2) NOT NULL CHECK (marks_percentage >= 0 AND marks_percentage <= 100),
    status VARCHAR(24) NOT NULL DEFAULT 'SUBMITTED'
        CHECK (status IN ('SUBMITTED', 'UNDER_REVIEW', 'APPROVED', 'REJECTED', 'WAITLISTED')),
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    decision_notes VARCHAR(1000),
    decision_at TIMESTAMPTZ,
    decided_by_user_id BIGINT REFERENCES user_accounts(id),
    CONSTRAINT uk_admission_student_course UNIQUE (student_id, course_id)
);

CREATE TABLE IF NOT EXISTS admission_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL UNIQUE REFERENCES admission_applications(id),
    admission_number VARCHAR(40) NOT NULL UNIQUE,
    admitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_admission_status ON admission_applications(status);
CREATE INDEX IF NOT EXISTS idx_admission_submitted ON admission_applications(submitted_at);
CREATE INDEX IF NOT EXISTS idx_admission_course ON admission_applications(course_id);

COMMIT;
